function deduplicateRepositories(list) {
    const seen = new Set();

    return list.filter((repo) => {
        const key = repo.fullName.trim().toLowerCase();
        if (seen.has(key)) {
            return false;
        }

        seen.add(key);
        return true;
    });
}

function formatRepositoryTitle(name) {
    return name
        .replace(/[-_]+/g, ' ')
        .replace(/\s+/g, ' ')
        .trim()
        .replace(/\b\w/g, (char) => char.toUpperCase());
}


function computeLogoHue(seedText) {
    let hash = 0;

    for (let index = 0; index < seedText.length; index += 1) {
        hash = (hash * 31 + seedText.charCodeAt(index)) % 360;
    }

    return hash;
}

function getRepositoryDescription(repo) {
    if (featuredDescriptions[repo.name]) {
        return featuredDescriptions[repo.name];
    }

    const languageText = repo.language !== '-' ? `${repo.language} ` : '';
    return `A ${repo.visibility} ${languageText}repository from my GitHub portfolio. Open this project to explore source code, commits, and updates.`;
}

function createArrowIcon() {
    const iconWrap = document.createElement('span');
    iconWrap.setAttribute('aria-hidden', 'true');

    iconWrap.innerHTML = `
        <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" class="arrow-icon">
            <path stroke-linecap="round" stroke-linejoin="round" d="M4.5 19.5l15-15m0 0H8.25m11.25 0v11.25" />
        </svg>
    `;

    return iconWrap;
}

function createActionButton(label, url) {
    const button = document.createElement('button');
    button.className = 'animated-button';
    button.type = 'button';

    const textWrap = document.createElement('span');
    const text = document.createElement('span');
    text.textContent = label;

    textWrap.appendChild(text);
    textWrap.appendChild(createArrowIcon());
    button.appendChild(textWrap);

    button.addEventListener('click', () => {
        window.open(url, '_blank', 'noopener,noreferrer');
    });

    return button;
}

function createMetaBadge(text) {
    const badge = document.createElement('span');
    badge.className = 'meta-badge';
    badge.textContent = text;
    return badge;
}

function createProjectCard(repo) {
    const card = document.createElement('article');
    card.className = 'project-card';

    const image = document.createElement('img');
    image.className = 'project-image';
    image.alt = repo.name;
    image.loading = 'lazy';
    image.src = `https://opengraph.githubassets.com/1/${repo.fullName}`;

    const title = document.createElement('h2');
    title.className = 'project-title';
    title.textContent = formatRepositoryTitle(repo.name);

    const meta = document.createElement('div');
    meta.className = 'project-meta';
    meta.appendChild(createMetaBadge(repo.visibility));

    const lang = (repo.language && repo.language !== '-' && repo.language !== 'null') ? repo.language : 'Other';
    meta.appendChild(createMetaBadge(lang));

    const description = document.createElement('p');
    description.className = 'project-description';
    description.textContent = getRepositoryDescription(repo);

    const buttonGroup = document.createElement('div');
    buttonGroup.className = 'button-group';
    buttonGroup.appendChild(createActionButton('GitHub Repo', repo.url));

    if (liveDemoLinks[repo.name]) {
        buttonGroup.appendChild(createActionButton('Live Demo', liveDemoLinks[repo.name]));
    }

    card.appendChild(image);
    card.appendChild(title);
    card.appendChild(meta);
    card.appendChild(description);
    card.appendChild(buttonGroup);

    return card;
}

function renderCategoryFilters(uniqueRepositories, currentFilter) {
    if (!categoryFilterContainer) return;
    categoryFilterContainer.innerHTML = '';

    const categories = new Set(['All']);
    uniqueRepositories.forEach(repo => {
        const lang = (repo.language && repo.language !== '-' && repo.language !== 'null') ? repo.language : 'Other';
        categories.add(lang);
    });

    Array.from(categories).sort().forEach(category => {
        const btn = document.createElement('button');
        btn.className = `filter-btn ${category === currentFilter ? 'active' : ''}`;
        btn.textContent = category;
        btn.addEventListener('click', () => renderProjects(category));
        categoryFilterContainer.appendChild(btn);
    });
}

function renderProjects(filter = 'All') {
    const uniqueRepositories = deduplicateRepositories(repositories);

    let filteredRepositories = uniqueRepositories;
    if (filter !== 'All') {
        filteredRepositories = uniqueRepositories.filter(repo => {
            const lang = (repo.language && repo.language !== '-' && repo.language !== 'null') ? repo.language : 'Other';
            return lang === filter;
        });
    }

    const duplicateCount = repositories.length - uniqueRepositories.length;
    projectsSummary.textContent = `${filteredRepositories.length} repositories listed (${duplicateCount} duplicates removed). Filter: ${filter}`;

    renderCategoryFilters(uniqueRepositories, filter);

    projectsContainer.innerHTML = '';
    filteredRepositories.forEach((repo) => {
        projectsContainer.appendChild(createProjectCard(repo));
    });
}

function triggerTransition(url) {
    const transition = document.createElement('div');
    transition.className = 'page-transition active';
    document.body.appendChild(transition);

    setTimeout(() => {
        window.location.href = url;
    }, 500);
}

function goBack() {
    triggerTransition('index.html');
}

window.goBack = goBack;

document.addEventListener('DOMContentLoaded', () => {
    const themeToggle = document.getElementById('theme-toggle');
    const body = document.body;
    const icon = themeToggle.querySelector('i');

    const applySavedTheme = () => {
        const savedTheme = localStorage.getItem('theme');

        if (savedTheme === 'dark') {
            body.classList.add('dark-mode');
            icon.classList.remove('fa-sun');
            icon.classList.add('fa-moon');
            return;
        }

        body.classList.remove('dark-mode');
        icon.classList.remove('fa-moon');
        icon.classList.add('fa-sun');
    };

    themeToggle.addEventListener('click', () => {
        body.classList.toggle('dark-mode');

        if (body.classList.contains('dark-mode')) {
            localStorage.setItem('theme', 'dark');
            icon.classList.remove('fa-sun');
            icon.classList.add('fa-moon');
            return;
        }

        localStorage.setItem('theme', 'light');
        icon.classList.remove('fa-moon');
        icon.classList.add('fa-sun');
    });

    window.addEventListener('popstate', () => {
        goBack();
    });

    history.pushState(null, '', window.location.href);
    applySavedTheme();
    renderProjects();
});
